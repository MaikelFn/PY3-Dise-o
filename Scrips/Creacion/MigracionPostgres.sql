-- CLICKMARKET - MIGRACIÓN UNIFICADA A POSTGRESQL (NEON)
-- Fuentes: 00_Crear_BD.sql, 01_Crear_Tablas(3).sql, 02_Crear_Datos_Iniciales.sql
-- Ejecutar conectado a neondb (no crear ni cambiar base de datos).
-- Requiere esquema public sin las tablas de ClickMarket existentes.
-- Una sola ejecución; transacción revierte todo si hay error.
BEGIN;

-- ============================================
-- CLICKMARKET - MODELO COMPLETO
-- 18 TABLAS
-- PostgreSQL / Neon
-- ============================================

-- 1. ROLES

CREATE TABLE public.Roles (
    RolID INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Nombre VARCHAR(30) NOT NULL UNIQUE,
    Descripcion VARCHAR(200) NULL,

    CONSTRAINT CK_Roles_Nombre
        CHECK (Nombre IN (
            'Comprador',
            'Vendedor',
            'Administrador'
        ))
);

-- 2. USUARIOS

CREATE TABLE public.Usuarios (
    UsuarioID INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    RolID INT NOT NULL,
    Nombre VARCHAR(100) NOT NULL,
    Apellido VARCHAR(100) NOT NULL,
    Correo VARCHAR(150) NOT NULL UNIQUE,
    ContrasenaHash VARCHAR(255) NOT NULL,
    FechaRegistro TIMESTAMP NOT NULL
        DEFAULT CURRENT_TIMESTAMP,
    Activo BOOLEAN NOT NULL DEFAULT TRUE,

    CONSTRAINT FK_Usuarios_Roles
        FOREIGN KEY (RolID)
        REFERENCES public.Roles(RolID)
);

-- 3. VENDEDORES

CREATE TABLE public.Vendedores (
    VendedorID INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    UsuarioID INT NULL UNIQUE,
    NombreComercial VARCHAR(150) NOT NULL,
    Descripcion VARCHAR(500) NULL,
    EsClickMarket BOOLEAN NOT NULL DEFAULT FALSE,
    Activo BOOLEAN NOT NULL DEFAULT TRUE,

    CONSTRAINT FK_Vendedores_Usuarios
        FOREIGN KEY (UsuarioID)
        REFERENCES public.Usuarios(UsuarioID),

    CONSTRAINT CK_Vendedores_Tipo
        CHECK (
            (EsClickMarket = TRUE AND UsuarioID IS NULL)
            OR
            (EsClickMarket = FALSE AND UsuarioID IS NOT NULL)
        )
);

CREATE UNIQUE INDEX UX_Vendedores_ClickMarket
ON public.Vendedores(EsClickMarket)
WHERE EsClickMarket = TRUE;

-- 4. DIRECCIONES

CREATE TABLE public.Direcciones (
    DireccionID INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    UsuarioID INT NOT NULL,
    Provincia VARCHAR(100) NOT NULL,
    Canton VARCHAR(100) NOT NULL,
    Distrito VARCHAR(100) NOT NULL,
    Detalle VARCHAR(300) NOT NULL,
    Principal BOOLEAN NOT NULL DEFAULT FALSE,

    CONSTRAINT FK_Direcciones_Usuarios
        FOREIGN KEY (UsuarioID)
        REFERENCES public.Usuarios(UsuarioID),

    CONSTRAINT UQ_Direcciones_UsuarioDireccion
        UNIQUE (UsuarioID, DireccionID)
);

CREATE UNIQUE INDEX UX_Direcciones_Principal
ON public.Direcciones(UsuarioID)
WHERE Principal = TRUE;

-- 5. CATEGORIAS

CREATE TABLE public.Categorias (
    CategoriaID INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Nombre VARCHAR(100) NOT NULL UNIQUE,
    Descripcion VARCHAR(300) NULL,
    Activa BOOLEAN NOT NULL DEFAULT TRUE
);

-- 6. PRODUCTOS

CREATE TABLE public.Productos (
    ProductoID INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    VendedorID INT NOT NULL,
    CategoriaID INT NOT NULL,
    Nombre VARCHAR(150) NOT NULL,
    Descripcion TEXT NULL,
    Precio DECIMAL(12,2) NOT NULL,
    FechaCreacion TIMESTAMP NOT NULL
        DEFAULT CURRENT_TIMESTAMP,
    Activo BOOLEAN NOT NULL DEFAULT TRUE,

    CONSTRAINT FK_Productos_Vendedores
        FOREIGN KEY (VendedorID)
        REFERENCES public.Vendedores(VendedorID),

    CONSTRAINT FK_Productos_Categorias
        FOREIGN KEY (CategoriaID)
        REFERENCES public.Categorias(CategoriaID),

    CONSTRAINT CK_Productos_Precio
        CHECK (Precio >= 0)
);

-- 7. IMAGENES DE PRODUCTOS

CREATE TABLE public.ImagenesProducto (
    ImagenID INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ProductoID INT NOT NULL,
    ImagenURL VARCHAR(500) NOT NULL,
    EsPrincipal BOOLEAN NOT NULL DEFAULT FALSE,
    Orden INT NOT NULL DEFAULT 0,

    CONSTRAINT FK_ImagenesProducto_Productos
        FOREIGN KEY (ProductoID)
        REFERENCES public.Productos(ProductoID),

    CONSTRAINT CK_ImagenesProducto_Orden
        CHECK (Orden >= 0)
);

CREATE UNIQUE INDEX UX_ImagenesProducto_Principal
ON public.ImagenesProducto(ProductoID)
WHERE EsPrincipal = TRUE;

-- 8. INVENTARIOS

CREATE TABLE public.Inventarios (
    InventarioID INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ProductoID INT NOT NULL UNIQUE,
    CantidadDisponible INT NOT NULL DEFAULT 0,
    CantidadReservada INT NOT NULL DEFAULT 0,

    CONSTRAINT FK_Inventarios_Productos
        FOREIGN KEY (ProductoID)
        REFERENCES public.Productos(ProductoID),

    CONSTRAINT CK_Inventarios_Cantidades
        CHECK (
            CantidadDisponible >= 0
            AND CantidadReservada >= 0
        )
);

-- 9. CARRITOS

CREATE TABLE public.Carritos (
    CarritoID INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    UsuarioID INT NOT NULL UNIQUE,
    FechaCreacion TIMESTAMP NOT NULL
        DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT FK_Carritos_Usuarios
        FOREIGN KEY (UsuarioID)
        REFERENCES public.Usuarios(UsuarioID)
);

-- 10. DETALLES DEL CARRITO

CREATE TABLE public.DetallesCarrito (
    DetalleCarritoID INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CarritoID INT NOT NULL,
    ProductoID INT NOT NULL,
    Cantidad INT NOT NULL,

    CONSTRAINT FK_DetallesCarrito_Carritos
        FOREIGN KEY (CarritoID)
        REFERENCES public.Carritos(CarritoID),

    CONSTRAINT FK_DetallesCarrito_Productos
        FOREIGN KEY (ProductoID)
        REFERENCES public.Productos(ProductoID),

    CONSTRAINT UQ_DetallesCarrito_Producto
        UNIQUE (CarritoID, ProductoID),

    CONSTRAINT CK_DetallesCarrito_Cantidad
        CHECK (Cantidad > 0)
);

-- 11. ESTADOS DE PEDIDO

CREATE TABLE public.EstadosPedido (
    EstadoPedidoID INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Nombre VARCHAR(30) NOT NULL UNIQUE,
    Descripcion VARCHAR(200) NULL,

    CONSTRAINT CK_EstadosPedido_Nombre
        CHECK (Nombre IN (
            'Pendiente',
            'Confirmado',
            'Enviado',
            'Entregado',
            'Cancelado'
        ))
);

-- 12. PEDIDOS

CREATE TABLE public.Pedidos (
    PedidoID INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    UsuarioID INT NOT NULL,
    DireccionID INT NOT NULL,
    EstadoPedidoID INT NOT NULL,
    FechaPedido TIMESTAMP NOT NULL
        DEFAULT CURRENT_TIMESTAMP,
    Subtotal DECIMAL(12,2) NOT NULL,
    CostoEnvio DECIMAL(12,2) NOT NULL DEFAULT 0,
    Total DECIMAL(12,2) NOT NULL,

    CONSTRAINT FK_Pedidos_Usuarios
        FOREIGN KEY (UsuarioID)
        REFERENCES public.Usuarios(UsuarioID),

    CONSTRAINT FK_Pedidos_Direcciones_Usuario
        FOREIGN KEY (UsuarioID, DireccionID)
        REFERENCES public.Direcciones(UsuarioID, DireccionID),

    CONSTRAINT FK_Pedidos_Estados
        FOREIGN KEY (EstadoPedidoID)
        REFERENCES public.EstadosPedido(EstadoPedidoID),

    CONSTRAINT CK_Pedidos_Montos
        CHECK (
            Subtotal >= 0
            AND CostoEnvio >= 0
            AND Total = Subtotal + CostoEnvio
        )
);

-- 13. DETALLES DEL PEDIDO

CREATE TABLE public.DetallesPedido (
    DetallePedidoID INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    PedidoID INT NOT NULL,
    ProductoID INT NOT NULL,
    Cantidad INT NOT NULL,
    PrecioUnitario DECIMAL(12,2) NOT NULL,
    Subtotal DECIMAL(12,2) NOT NULL,

    CONSTRAINT FK_DetallesPedido_Pedidos
        FOREIGN KEY (PedidoID)
        REFERENCES public.Pedidos(PedidoID),

    CONSTRAINT FK_DetallesPedido_Productos
        FOREIGN KEY (ProductoID)
        REFERENCES public.Productos(ProductoID),

    CONSTRAINT CK_DetallesPedido_Valores
        CHECK (
            Cantidad > 0
            AND PrecioUnitario >= 0
            AND Subtotal = Cantidad * PrecioUnitario
        )
);

-- 14. METODOS DE PAGO

CREATE TABLE public.MetodosPago (
    MetodoPagoID INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Nombre VARCHAR(50) NOT NULL UNIQUE,
    Descripcion VARCHAR(200) NULL,
    Activo BOOLEAN NOT NULL DEFAULT TRUE
);

-- 15. PAGOS SIMULADOS

CREATE TABLE public.Pagos (
    PagoID INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    PedidoID INT NOT NULL,
    MetodoPagoID INT NOT NULL,
    Monto DECIMAL(12,2) NOT NULL,
    Estado VARCHAR(20) NOT NULL DEFAULT 'Pendiente',
    FechaPago TIMESTAMP NULL,

    CONSTRAINT FK_Pagos_Pedidos
        FOREIGN KEY (PedidoID)
        REFERENCES public.Pedidos(PedidoID),

    CONSTRAINT FK_Pagos_Metodos
        FOREIGN KEY (MetodoPagoID)
        REFERENCES public.MetodosPago(MetodoPagoID),

    CONSTRAINT CK_Pagos_Estado
        CHECK (Estado IN (
            'Pendiente',
            'Aprobado',
            'Rechazado'
        )),

    CONSTRAINT CK_Pagos_Monto
        CHECK (Monto >= 0)
);

-- 16. TIPOS DE ENVIO

CREATE TABLE public.TiposEnvio (
    TipoEnvioID INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Nombre VARCHAR(50) NOT NULL UNIQUE,
    CostoBase DECIMAL(10,2) NOT NULL,
    Descripcion VARCHAR(200) NULL,
    Activo BOOLEAN NOT NULL DEFAULT TRUE
);

-- 17. ENVIOS

CREATE TABLE public.Envios (
    EnvioID INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    PedidoID INT NOT NULL UNIQUE,
    TipoEnvioID INT NOT NULL,
    Costo DECIMAL(12,2) NOT NULL,
    Estado VARCHAR(20) NOT NULL DEFAULT 'Pendiente',
    FechaEnvio TIMESTAMP NULL,
    FechaEntrega TIMESTAMP NULL,

    CONSTRAINT FK_Envios_Pedidos
        FOREIGN KEY (PedidoID)
        REFERENCES public.Pedidos(PedidoID),

    CONSTRAINT FK_Envios_Tipos
        FOREIGN KEY (TipoEnvioID)
        REFERENCES public.TiposEnvio(TipoEnvioID),

    CONSTRAINT CK_Envios_Estado
        CHECK (Estado IN (
            'Pendiente',
            'Preparando',
            'Enviado',
            'Entregado'
        )),

    CONSTRAINT CK_Envios_Costo
        CHECK (Costo >= 0),

    CONSTRAINT CK_Envios_Fechas
        CHECK (
            FechaEntrega IS NULL
            OR (
                FechaEnvio IS NOT NULL
                AND FechaEntrega >= FechaEnvio
            )
        )
);

-- 18. NOTIFICACIONES

CREATE TABLE public.Notificaciones (
    NotificacionID INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    UsuarioID INT NOT NULL,
    PedidoID INT NULL,
    Titulo VARCHAR(150) NOT NULL,
    Mensaje VARCHAR(500) NOT NULL,
    Leida BOOLEAN NOT NULL DEFAULT FALSE,
    FechaCreacion TIMESTAMP NOT NULL
        DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT FK_Notificaciones_Usuarios
        FOREIGN KEY (UsuarioID)
        REFERENCES public.Usuarios(UsuarioID),

    CONSTRAINT FK_Notificaciones_Pedidos
        FOREIGN KEY (PedidoID)
        REFERENCES public.Pedidos(PedidoID)
);

-- ============================================
-- INDICES ADICIONALES
-- ============================================

CREATE INDEX IX_Productos_Categoria
ON public.Productos(CategoriaID);

CREATE INDEX IX_Productos_Vendedor
ON public.Productos(VendedorID);

CREATE INDEX IX_Pedidos_Usuario_Fecha
ON public.Pedidos(UsuarioID, FechaPedido DESC);

CREATE INDEX IX_DetallesPedido_Pedido
ON public.DetallesPedido(PedidoID);

CREATE INDEX IX_Pagos_Pedido
ON public.Pagos(PedidoID);

CREATE INDEX IX_Notificaciones_Usuario_Leida
ON public.Notificaciones(UsuarioID, Leida);


